-- 1. USERS TABLE (Student & Admin Accounts)
CREATE TABLE IF NOT EXISTS public.users (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120) UNIQUE NOT NULL,
    phone VARCHAR(30) DEFAULT '',
    password VARCHAR(100) NOT NULL,
    role VARCHAR(20) DEFAULT 'student',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. COURSES TABLE
CREATE TABLE IF NOT EXISTS public.courses (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(200) NOT NULL,
    category VARCHAR(100) NOT NULL,
    description TEXT NOT NULL,
    duration VARCHAR(50) NOT NULL,
    price NUMERIC(10, 2) NOT NULL,
    discount_price NUMERIC(10, 2) NOT NULL,
    level VARCHAR(50) DEFAULT 'Beginner to Advanced',
    rating NUMERIC(3, 2) DEFAULT 4.80,
    reviews_count INT DEFAULT 120,
    image_url TEXT DEFAULT '',
    syllabus_json JSONB DEFAULT '[]'::jsonb,
    trainer_name VARCHAR(100) NOT NULL,
    trainer_role VARCHAR(150) NOT NULL,
    mode VARCHAR(50) DEFAULT 'Online & Offline',
    tags TEXT DEFAULT 'Top Rated, Job Guarantee'
);

-- 3. BATCHES TABLE
CREATE TABLE IF NOT EXISTS public.batches (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    course_id BIGINT REFERENCES public.courses(id) ON DELETE CASCADE,
    batch_code VARCHAR(50) UNIQUE NOT NULL,
    start_date VARCHAR(50) NOT NULL,
    timings VARCHAR(100) NOT NULL,
    mode VARCHAR(50) DEFAULT 'Live Online',
    seats_total INT DEFAULT 30,
    seats_left INT DEFAULT 5,
    instructor VARCHAR(100) NOT NULL,
    status VARCHAR(50) DEFAULT 'Filling Fast'
);

-- 4. ENROLLMENTS TABLE
CREATE TABLE IF NOT EXISTS public.enrollments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_name VARCHAR(100) NOT NULL,
    student_email VARCHAR(120) NOT NULL,
    student_phone VARCHAR(30) NOT NULL,
    course_id BIGINT NOT NULL,
    course_title VARCHAR(200) NOT NULL,
    batch_code VARCHAR(50) NOT NULL,
    total_fee NUMERIC(10, 2) NOT NULL,
    payment_status VARCHAR(50) DEFAULT 'Completed',
    enrolled_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 5. DEMO BOOKINGS TABLE
CREATE TABLE IF NOT EXISTS public.demo_bookings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    course_interest VARCHAR(200) NOT NULL,
    slot_date VARCHAR(50) NOT NULL,
    slot_time VARCHAR(50) NOT NULL,
    status VARCHAR(50) DEFAULT 'Confirmed',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 6. INQUIRIES TABLE
CREATE TABLE IF NOT EXISTS public.inquiries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL,
    email VARCHAR(120) NOT NULL,
    phone VARCHAR(30) NOT NULL,
    course_name VARCHAR(200) DEFAULT '',
    message TEXT NOT NULL,
    status VARCHAR(50) DEFAULT 'New',
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 7. CERTIFICATES TABLE
CREATE TABLE IF NOT EXISTS public.certificates (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    certificate_code VARCHAR(50) UNIQUE NOT NULL,
    student_name VARCHAR(100) NOT NULL,
    course_title VARCHAR(200) NOT NULL,
    issue_date VARCHAR(50) NOT NULL,
    grade VARCHAR(20) DEFAULT 'Distinction (A+)',
    instructor_name VARCHAR(100) DEFAULT 'Dr. Aris Vance'
);

