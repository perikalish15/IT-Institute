ALTER TABLE public.demo_bookings ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.inquiries ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.certificates ENABLE ROW LEVEL SECURITY;

-- Allow Public Anonymous Read & Write
CREATE POLICY "Public Read Users" ON public.users FOR SELECT USING (true);
CREATE POLICY "Public Insert Users" ON public.users FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Courses" ON public.courses FOR SELECT USING (true);
CREATE POLICY "Public Insert Courses" ON public.courses FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Batches" ON public.batches FOR SELECT USING (true);
CREATE POLICY "Public Insert Batches" ON public.batches FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Enrollments" ON public.enrollments FOR SELECT USING (true);
CREATE POLICY "Public Insert Enrollments" ON public.enrollments FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Demo Bookings" ON public.demo_bookings FOR SELECT USING (true);
CREATE POLICY "Public Insert Demo Bookings" ON public.demo_bookings FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Inquiries" ON public.inquiries FOR SELECT USING (true);
CREATE POLICY "Public Insert Inquiries" ON public.inquiries FOR INSERT WITH CHECK (true);

CREATE POLICY "Public Read Certificates" ON public.certificates FOR SELECT USING (true);
CREATE POLICY "Public Insert Certificates" ON public.certificates FOR INSERT WITH CHECK (true);

